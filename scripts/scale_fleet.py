#!/usr/bin/env python3
"""Write a load-test fleet: N stand-ins, a mix of all 22 platform types, spread over the Bay
area so they don't stack (aircraft over the whole area, ground vehicles and small aircraft
on land around the Bay, boats in the Bay and offshore, AUVs offshore).

    .venv/bin/python scripts/scale_fleet.py 1000            # sim/fleets/scale-1000.toml
    .venv/bin/python scripts/scale_fleet.py 3000 -o sim/run/scale-3000.toml
    .venv/bin/python scripts/scale_fleet.py 800 --swarm=-122.465,37.818,560 -o sim/run/swarm-800.toml

Every platform runs as a stand-in (`sim = "standin"`), whatever the catalog says, so one
engine process carries the whole fleet. Without tidewater the land/water placement is
cosmetic; with it, ground and marine stand-ins start where they belong.
"""

import argparse
import math
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# per 1,000 nodes: air 440, ground 140, surface 280, subsurface 140
MIX = {
    "rq4": 20, "mq9b_armed": 40, "cca": 40, "fvr90": 50, "puma": 60, "switchblade": 50, "x10": 80,
    "fpv": 80, "lta": 20,
    "ugv_logistics": 40, "ugv_armed": 30, "ugv_mines": 20, "ugv_recon": 40, "tracker": 10,
    "magura": 70, "corsair": 40, "seahunter": 30, "saildrone": 60, "buoy": 80,
    "bluerov": 50, "remus": 60, "orca": 30,
}

# low-lying land around the Bay (lat, lon, ground alt m)
LAND = [(37.805, -122.455, 5), (37.785, -122.305, 5), (37.752, -122.205, 10), (37.620, -122.390, 5),
        (37.415, -122.055, 10), (38.060, -122.515, 5), (37.925, -122.355, 10), (37.650, -122.140, 10),
        (37.985, -122.055, 15), (37.825, -122.372, 5)]
# open water inside the Bay
BAY = [(37.840, -122.430), (37.760, -122.345), (37.600, -122.230), (38.040, -122.380), (37.895, -122.400)]
# offshore, west of the Golden Gate (lines run east, so stay clear of the coast)
OFFSHORE = [(lat, lon) for lat in (37.56, 37.62, 37.68, 37.74, 37.80, 37.85)
            for lon in (-123.05, -122.95, -122.85, -122.77)]
# the whole area, for aircraft on station
AREA = [(lat, lon) for lat in (37.45, 37.60, 37.75, 37.90, 38.05) for lon in (-123.0, -122.75, -122.5, -122.25, -122.0)]

ON_STATION = {"rq4", "mq9b_armed", "cca"}  # HALE/MALE/CCA start airborne at cruise altitude (the MQ-9B armed: rules 24)
OFFSHORE_ONLY = {"remus", "orca"}  # AUVs need depth


def where(pid, spec):
    """(spawn sites, spacing between vehicles of a unit in m, start alt or None for the site's)."""
    domain = spec["domain"]
    if pid in ON_STATION:
        return AREA, 3000, spec["alt_m"]
    if domain in ("air", "ground"):
        return LAND, 60, None
    if pid in OFFSHORE_ONLY:
        return OFFSHORE, 600, 0
    if domain == "subsurface":
        return BAY, 150, 0
    return BAY + OFFSHORE, 250 if pid != "buoy" else 400, 0


def counts(n):
    raw = {p: w * n / 1000 for p, w in MIX.items()}
    out = {p: max(1, math.floor(r)) for p, r in raw.items()}
    for p in sorted(raw, key=lambda p: raw[p] - math.floor(raw[p]), reverse=True):
        if sum(out.values()) >= n:
            break
        out[p] += 1
    while sum(out.values()) > n:  # tiny n: trim the largest
        out[max(out, key=out.get)] -= 1
    return out


def swarm(n, center, radius_m, types, platforms):
    """A dense swarm: n small aircraft packed in a disk, rows running east, the types taking
    turns row by row, the rows' altitudes staggered 60 to 400 m. A fixed-wing stand-in spawned
    above 50 m starts on station and loiters, so the swarm moves from the start with no order;
    a copter spawns landed and disarmed and would sit still until ordered."""
    lon0, lat0 = center
    for t in types:
        if platforms[t]["domain"] != "air":
            raise SystemExit(f"{t} is not an aircraft")
        if platforms[t].get("vehicle") != "plane":
            print(f"note: {t} is a {platforms[t].get('vehicle')}: it spawns landed and stays put until ordered")
    spacing = math.sqrt(math.pi * radius_m**2 / n)
    kx = 111_320.0 * math.cos(math.radians(lat0))
    rows, y = [], -radius_m + spacing / 2
    while y < radius_m:
        half = math.sqrt(max(0.0, radius_m**2 - y**2))
        rows.append((y, -half + spacing / 2, max(1, int(2 * half / spacing))))
        y += spacing
    total = sum(r[2] for r in rows)
    lines = [f"# LOAD TEST ONLY: a dense swarm of {n} small aircraft in a {radius_m:.0f} m disk at",
             f"# {lon0}, {lat0}. Generated by scripts/scale_fleet.py --swarm; regenerate rather than edit.",
             f'title = "Swarm test: {n} {"/".join(types)} stand-ins"', ""]
    left = n
    for i, (y, x0, k) in enumerate(rows):
        count = min(left, round(k * n / total)) if i < len(rows) - 1 else left
        if count <= 0:
            continue
        left -= count
        alt = 60 + (i * 97) % 341  # staggered, 60 to 400 m
        lat, lon = lat0 + y / 111_320.0, lon0 + x0 / kx
        lines += ["[[unit]]", f'platform = "{types[i % len(types)]}"', f"count = {count}", 'sim = "standin"',
                  f"spawn = [{lat:.5f}, {lon:.5f}, {alt}, {(i * 47) % 360}]", f"spacing_m = {spacing:.1f}", ""]
        if left <= 0:
            break
    return lines


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("n", type=int, nargs="?", default=1000)
    ap.add_argument("-o", "--out", help="default sim/fleets/scale-<n>.toml (swarm-<n>.toml with --swarm)")
    ap.add_argument("--swarm", metavar="LON,LAT,RADIUS_M",
                    help="a dense swarm instead: n small aircraft packed in this disk (e.g. --swarm=-122.465,37.818,560 for "
                         "about 1 km2 just inside the Golden Gate)")
    ap.add_argument("--types", default="puma,switchblade",
                    help="the swarm's platforms, comma separated (default the small fixed-wing types, which fly from the start)")
    args = ap.parse_args()
    platforms = tomllib.loads((ROOT / "sim" / "platforms.toml").read_text())
    if args.swarm:
        lon, lat, r = (float(x) for x in args.swarm.split(","))
        lines = swarm(args.n, (lon, lat), r, args.types.split(","), platforms)
        out = Path(args.out) if args.out else ROOT / "sim" / "fleets" / f"swarm-{args.n}.toml"
        out.write_text("\n".join(lines))
        print(f"wrote {out}")
        return
    unit_size = max(10, math.ceil(args.n / 100))
    uses = {}  # site -> units placed there so far (each next unit starts further north)
    lines = [f"# LOAD TEST ONLY: {args.n} stand-ins, a mix of all {len(MIX)} platform types spread over",
             "# the Bay area. Generated by scripts/scale_fleet.py; regenerate rather than edit.",
             f"# make up FLEET=scale-{args.n}",
             f'title = "Scale test: {args.n} stand-ins, all platform types"', ""]
    for pid, total in counts(args.n).items():
        spec = platforms[pid]
        sites, spacing, alt = where(pid, spec)
        k = 0
        while total > 0:
            count = min(unit_size, total)
            total -= count
            site = sites[(hash_pid(pid) + k) % len(sites)]
            k += 1
            row = uses.get(site, 0)
            uses[site] = row + 1
            # rows 400 m apart northwards (8 km for aircraft on station), lines run east
            north = row * (8000 if pid in ON_STATION else 400)
            lat = site[0] + north / 111_320.0
            lon = site[1]
            a = alt if alt is not None else site[2]
            lines += ["[[unit]]", f'platform = "{pid}"', f"count = {count}", 'sim = "standin"',
                      f"spawn = [{lat:.4f}, {lon:.4f}, {a}, 0]", f"spacing_m = {spacing}", ""]
    out = Path(args.out) if args.out else ROOT / "sim" / "fleets" / f"scale-{args.n}.toml"
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


def hash_pid(pid):
    """A stable spread of platforms over sites (str hash is salted per run)."""
    return sum(ord(c) * (i + 1) for i, c in enumerate(pid))


if __name__ == "__main__":
    main()
