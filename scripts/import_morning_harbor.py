#!/usr/bin/env python3
"""Rebuild the bundled Golden Gate AIS replay, offline and without dependencies.

Source rows remain in sim/data/morning-harbor-watch/ais.csv; provenance.json records
the upstream object, query and license. --check checks the committed derived file.
"""

from __future__ import annotations

import argparse
import csv
import datetime as dt
import hashlib
import json
import math
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "sim/data/morning-harbor-watch"
OUTPUT = ROOT / "sim/scenarios/morning-harbor-watch.toml"
WEATHER = DATA / "weather.json"
START = dt.datetime(2024, 6, 14, 15, tzinfo=dt.timezone.utc)


def number(raw: str, upper: float) -> float | None:
    if not raw:
        return None
    value = float(raw)
    return value if math.isfinite(value) and 0 <= value < upper else None


def vessel_kind(code: str) -> tuple[str, str]:
    """Coarse simulation classes, not an identification of the actual hull or mission."""
    t = int(code) if code else 0
    if t == 30:
        return "fishing_vessel", "fishing"
    if t == 36:
        return "sailboat", "pleasure"
    if t == 37:
        return "small_fast_boat", "pleasure"
    if 40 <= t <= 49 or 60 <= t <= 69:
        return "ferry", "passenger"
    if 80 <= t <= 89:
        return "tanker", "tanker"
    if 70 <= t <= 79:
        return "cargo_ship", "cargo"
    if t in (31, 32, 52):
        return "patrol_boat", "tug"
    return "patrol_boat", "other"


def render(data: Path = DATA) -> str:
    meta = json.loads((data / "provenance.json").read_text())
    source = data / "ais.csv"
    if hashlib.sha256(source.read_bytes()).hexdigest() != meta["sha256"]:
        raise ValueError("AIS source checksum differs from provenance.json")
    groups: dict[str, list[dict[str, str]]] = defaultdict(list)
    with source.open(newline="") as f:
        for row in csv.DictReader(f):
            groups[row["mmsi"]].append(row)
    lines = [
        '# Generated by scripts/import_morning_harbor.py. Do not edit: source/provenance in',
        '# sim/data/morning-harbor-watch/. Recorded movement; all sensing is simulated.',
        'title = "Morning harbor watch: recorded AIS, 14 June 2024, 08:00-09:00 PDT"',
        'seed = 11', '', '[sensing]', 'model = "physical"',
        'misclassification_rate = 0.02',
        'terrain = "sim/headless/terrain/golden-gate.grid.gz"', '',
        '[sensing.weather]', 'archive = "sim/data/morning-harbor-watch/weather.json"', '',
        '# Wind uses the archived station series, assumed uniform across the scene.',
        '# Visibility and sea state are assumptions; wind_mps is the out-of-archive fallback.',
        '# No historical current field or tidal forcing is applied.',
        '[conditions]', 'wind_mps = 2.7', 'visibility_m = 10000', 'sea_state = 2', '',
    ]
    for mmsi, rows in sorted(groups.items()):
        rows.sort(key=lambda r: r["base_date_time"])
        kind, ship_type = vessel_kind(next((r["vessel_type"] for r in rows if r["vessel_type"]), ""))
        name = next((r["vessel_name"].strip() for r in rows if r["vessel_name"].strip()), "")
        # Transceiver is A/B in this NOAA product. Missing carriage is not guessed from hull type.
        carriage = next((r["transceiver"].lower() for r in rows if r["transceiver"] in ("A", "B")), None)
        lines += [
            '[[contact]]', f'id = "ais-{mmsi}"',
            f'name = {json.dumps(name or "AIS " + mmsi)}',
            'affiliation = "neutral"', 'domain = "surface"', f'kind = "{kind}"',
            'motion = "recorded"', 'max_gap_s = 300',
            f'ais = {{ mmsi = "{mmsi}", name = {json.dumps(name)}, ship_type = "{ship_type}" }}',
        ]
        if carriage:
            lines.append(f'ais_class = "{carriage}"')
        length = next((number(r["length"], 1000) for r in rows if number(r["length"], 1000)), None)
        if length is not None:
            lines.append(f'dc_m = {length:g}')
        lines.append('samples = [')
        previous = -1.0
        for row in rows:
            timestamp = dt.datetime.fromisoformat(row["base_date_time"]).replace(tzinfo=dt.timezone.utc)
            seconds = (timestamp - START).total_seconds()
            lon, lat = float(row["lon"]), float(row["lat"])
            if not (previous < seconds < 3600 and seconds >= 0 and -122.56 <= lon <= -122.38 and 37.77 <= lat <= 37.88):
                raise ValueError(f"invalid, duplicate or out-of-clip fix for {mmsi}: {row}")
            previous = seconds
            fields = [f'at_s = {seconds:g}', f'position = [{lon:.5f}, {lat:.5f}]']
            speed, course = number(row["sog"], 102.3), number(row["cog"], 360)
            if speed is not None:
                fields.append(f'speed_mps = {speed * 1852 / 3600:.6f}')
            if course is not None:
                fields.append(f'course_deg = {course:.4f}')
            lines.append('  { ' + ', '.join(fields) + ' },')
        lines += [']', '']
    return '\n'.join(lines)


def render_weather(data: Path = DATA) -> str:
    """Six-minute mean wind only. The weather schema's hourly gust semantics do not fit
    CO-OPS gust samples, which remain available in the untouched source file instead."""
    raw = (data / "wind.json").read_bytes()
    source = json.loads(raw)
    station = source["response"]["metadata"]
    rows = []
    for row in source["response"]["data"]:
        timestamp = dt.datetime.fromisoformat(row["t"]).replace(tzinfo=dt.timezone.utc)
        speed, bearing = float(row["s"]), math.radians(float(row["d"]))
        rows.append({"t": timestamp.timestamp(), "values": {
            "wind_east_mps": -speed * math.sin(bearing),
            "wind_north_mps": -speed * math.cos(bearing),
        }})
    return json.dumps({
        "schema": 1, "source": source["url"],
        "model": "NOAA CO-OPS 9414290 mean wind; assumed uniform across this scene",
        "fetched_at": "2026-10-29", "raw_sha256": hashlib.sha256(raw).hexdigest(),
        "bounds": [-122.57, 37.74, -122.35, 37.90],
        "points": [{"lat": float(station["lat"]), "lon": float(station["lon"]), "rows": rows}],
    }, indent=2) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, result in ((OUTPUT, render()), (WEATHER, render_weather())):
        if args.check:
            if path.read_text() != result:
                raise SystemExit(f"{path} differs: run scripts/import_morning_harbor.py")
        else:
            path.write_text(result)
            print(path)
    if args.check:
        print("Morning harbor watch: source checksum and generated traffic/weather match")


if __name__ == "__main__":
    main()
